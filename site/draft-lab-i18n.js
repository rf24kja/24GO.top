export const UI_STRINGS=Object.freeze({en:EN,ru:RU,th:TH,es:ES,fr:FR,de:DE,pt:PT,zh:ZH});
export function uiText(locale,key){
 if(typeof key!=='string'||!Object.hasOwn(EN,key))throw new TypeError('Unknown interface string');
 const language=UI_LOCALES.includes(locale)?locale:'en';
 return UI_STRINGS[language][key] ?? EN[key];
}
export function applyUiLanguage(doc,language){
 const locale=UI_LOCALES.includes(language)?language:'en';
 doc.documentElement.lang=locale;
 for(const node of doc.querySelectorAll('[data-ui]')){
  node.textContent=uiText(locale,node.getAttribute('data-ui'));
 }
 for(const node of doc.querySelectorAll('[data-ui-placeholder]')){
  node.setAttribute('placeholder',uiText(locale,node.getAttribute('data-ui-placeholder')));
 }
 for(const node of doc.querySelectorAll('[data-ui-label]')){
  node.setAttribute('aria-label',uiText(locale,node.getAttribute('data-ui-label')));
 }
 return locale;
}
