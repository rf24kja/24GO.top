// All translations are keyed by a fixed, reviewable allowlist.
// Unknown locale/key combinations fail closed or fall back to English.
export const PATH_UI=Object.freeze({en:EN,ru:RU,th:TH,es:ES,fr:FR,de:DE,pt:PT,zh:ZH});
export function readingPathUiText(locale,key){
 if(typeof key!=='string'||!Object.hasOwn(EN,key))
  throw new TypeError('Unknown reading-path interface key');
 const lang=PATH_LOCALES.includes(locale)?locale:'en';
 return PATH_UI[lang][key]??EN[key];
}
export function applyReadingPathLocale(doc,locale){
 const lang=PATH_LOCALES.includes(locale)?locale:'en';
 doc.documentElement.lang=lang;
 for(const el of doc.querySelectorAll('[data-path-ui]'))
  el.textContent=readingPathUiText(lang,el.getAttribute('data-path-ui'));
 for(const el of doc.querySelectorAll('[data-path-ui-label]'))
  el.setAttribute('aria-label',readingPathUiText(lang,el.getAttribute('data-path-ui-label')));
 for(const el of doc.querySelectorAll('[data-path-ui-placeholder]'))
  el.setAttribute('placeholder',readingPathUiText(lang,el.getAttribute('data-path-ui-placeholder')));
 return lang;
}
